def print_comparison(branches: dict, batch_keys: list):
    """
    branches: OrderedDict  name -> results dict
    Prints one row per metric, one column per branch.
    """
    names  = list(branches.keys())
    col_w  = 14
    row_w  = 32

    # collect all metric keys (silhouette + lisi + pr)
    sample = next(iter(branches.values()))
    sil_keys  = list(sample.get("silhouette", {}).keys())
    lisi_keys = list(sample.get("lisi", {}).keys())

    header = f"\n{'=' * (row_w + col_w * len(names))}"
    print(header)
    print(f"  {'METRIC':<{row_w}}" +
          "".join(f"{n:>{col_w}}" for n in names))
    print(f"  {'-' * (row_w - 2)}" +
          "  " + "  ".join("-" * (col_w - 2) for _ in names))

    def row(label, vals):
        cells = []
        for v in vals:
            if v is None:
                cells.append(f"{'—':>{col_w}}")
            elif isinstance(v, float) and (v != v):   # NaN
                cells.append(f"{'nan':>{col_w}}")
            elif isinstance(v, float):
                cells.append(f"{v:>{col_w}.4f}")
            else:
                cells.append(f"{str(v):>{col_w}}")
        print(f"  {label:<{row_w}}" + "".join(cells))

    # silhouette
    if sil_keys:
        print(f"\n  {'— Silhouette (batch→0, label→1) —'}")
        for k in sil_keys:
            vals = [b.get("silhouette", {}).get(k) for b in branches.values()]
            row(k, vals)

    # LISI
    if lisi_keys:
        print(f"\n  {'— LISI (iLISI batch↑, cLISI label↓) —'}")
        for k in lisi_keys:
            vals = [b.get("lisi", {}).get(k) for b in branches.values()]
            row(k, vals)

    # kBET
    kbet_keys = list(next(iter(branches.values())).get("kbet", {}).keys())
    if kbet_keys:
        print(f"\n  {'— kBET (rejection rate ↓ = better mixing) —'}")
        for k in kbet_keys:
            vals = [b.get("kbet", {}).get(k) for b in branches.values()]
            row(k, vals)

    # Leiden
    leiden_keys = list(next(iter(branches.values())).get("leiden", {}).keys())
    if leiden_keys:
        print(f"\n  {'— Leiden clustering (ARI/NMI↑ = better compound separation) —'}")
        for k in leiden_keys:
            vals = [b.get("leiden", {}).get(k) for b in branches.values()]
            row(k, vals)

    # mAP + AUROC
    print(f"\n  {'— Replication quality (higher=better) —'}")
    row("mAP (mean)",   [b.get("map", {}).get("mean_ap")   for b in branches.values()])
    row("mAP (median)", [b.get("map", {}).get("median_ap") for b in branches.values()])
    row("% replicating (mAP)",
        [b.get("map", {}).get("percent_replicating") for b in branches.values()])
    row("AUROC (replicate vs null)",
        [b.get("auroc", {}).get("auroc_replicating") for b in branches.values()])
    row("n_compounds",
        [str(b.get("map", {}).get("n_compounds", "—")) for b in branches.values()])

    # Replicate-tightness vs batch-spread ratio
    rep_keys = list(next(iter(branches.values())).get("replicate_batch", {}).keys())
    if rep_keys:
        print(f"\n  {'— Replicate vs batch (ratio<1 = replicates tighter than batch-mates) —'}")
        for k in rep_keys:
            vals = [b.get("replicate_batch", {}).get(k) for b in branches.values()]
            row(k, vals)

    # Edge-well bias
    edge_sample = next(iter(branches.values())).get("edge_well", {})
    if edge_sample:
        print(f"\n  {'— Edge-well bias (silhouette→0 = position-bias removed) —'}")
        for k in ("edge_well_silhouette", "edge_well_centroid_d"):
            if k in edge_sample:
                vals = [b.get("edge_well", {}).get(k) for b in branches.values()]
                row(k, vals)

    # Top-k retrieval saturation
    topk_keys = sorted(
        next(iter(branches.values())).get("topk_recall", {}).keys(),
        key=lambda s: int(s.replace("recall_at", "")),
    )
    if topk_keys:
        print(f"\n  {'— Top-k recall (higher = same-compound neighbours rank tightly) —'}")
        for k in topk_keys:
            vals = [b.get("topk_recall", {}).get(k) for b in branches.values()]
            row(k, vals)

    print(f"{'=' * (row_w + col_w * len(names))}\n")


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def parse_args():
    parser = argparse.ArgumentParser(
        description="Compare Raw + all batch-corrected embeddings side by side",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--embeddings-dir", type=str, required=True,
                        help="Path to channelwise_embeddings dir")
    parser.add_argument("--meta-path", type=str, default=None,
                        help="Path to metadata parquet file. "
                             "Auto-detected from checkpoint config if not provided.")
    parser.add_argument("--control-key", type=str, default="DMSO")
    parser.add_argument("--batch-keys", nargs="+", default=None,
                        choices=["batch", "plate", "well"])
    parser.add_argument("--n-pca", type=int, default=50,
                        help="PCA components for the Raw branch")
    parser.add_argument("--n-samples", type=int, default=20_000,
                        help="Subsample size for silhouette / LISI / kBET")
    parser.add_argument("--aggregate-level", choices=["site", "well"], default="well",
                        help="Collapse per-site embeddings to per-well consensus "
                             "(median over the ~9 sites/well) BEFORE any metric. "
                             "'well' is the correct biological replicate unit and "
                             "removes site-level pseudoreplication that otherwise "
                             "saturates mAP/AUROC/kBET; 'site' scores the per-site rows "
                             "instead.")
    parser.add_argument("--lisi-perplexity", type=int, default=30)
    parser.add_argument("--leiden-k", type=int, default=15,
                        help="k-NN neighbours for Leiden graph")
    parser.add_argument("--leiden-resolution", type=float, default=1.0,
                        help="Resolution parameter for Leiden clustering (the thesis scores at 1.0)")
    parser.add_argument("--no-raw", action="store_true", help="Skip Raw branch")
    parser.add_argument("--skip-branches", nargs="*", default=[],
                        metavar="SUBDIR",
                        help="Subdir names to skip (e.g. --skip-branches scvi mnn). "
                             "Matches against the directory name (case-insensitive).")
    parser.add_argument("--no-silhouette-lisi", action="store_true",
                        help="Only compute mAP + AUROC (skip silhouette/LISI/kBET, faster)")
    parser.add_argument("--out-json", type=str, default=None)
    return parser.parse_args()


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
if __name__ == "__main__":
    args = parse_args()
    emb_dir = Path(args.embeddings_dir)

    # --- Batch keys ---
    if args.batch_keys is None:
        args.batch_keys = detect_batch_keys(emb_dir)
        if args.batch_keys is None:
            raise SystemExit(
                "Could not auto-detect batch keys. "
                "Pass --batch-keys explicitly (e.g. --batch-keys batch)."
            )

    # --- Meta path ---
    if args.meta_path is None:
        detected = detect_meta_path(emb_dir.parent)
        if detected is None:
            raise SystemExit(
                "Could not auto-detect meta path. "
                "Pass --meta-path explicitly (e.g. --meta-path source_3_w_neg.pq)."
            )
        args.meta_path = str(detected)
        print(f"Auto-detected meta path: {args.meta_path}")

    # --- Discover branches ---
    skip_set = {s.lower() for s in (args.skip_branches or [])}
    discovered = discover_branches(emb_dir, skip_set)

    n_total = (not args.no_raw) + len(discovered)
    step    = 0

    branches    = {}   # name -> results
    all_results = {}   # for JSON

    # ----------------------------------------------------------------------- #
    # RAW branch  (loads .npz, applies PCA)
    # ----------------------------------------------------------------------- #
    if not args.no_raw:
        step += 1
        print(f"\n[{step}/{n_total}] RAW branch ...")
        source_3 = pd.read_parquet(args.meta_path)
        source_3["Metadata_Sample_ID"] = source_3["Metadata_Sample_ID"].astype(str)

        X_tr, meta_tr = load_npz_with_meta(
            emb_dir / "train_channelwise_embeddings.npz", source_3, args.control_key)
        X_va, meta_va = load_npz_with_meta(
            emb_dir / "validation_channelwise_embeddings.npz", source_3, args.control_key)

        X_all    = np.vstack([X_tr, X_va])
        meta_all = pd.concat([meta_tr, meta_va], ignore_index=True)

        [_, Z_all_raw], n_comp, ev = pca_reduce(X_tr, [X_tr, X_all], args.n_pca)
        print(f"  PCA {X_tr.shape[1]}D -> {n_comp}D  (explained var: {ev:.3f})")

        if args.aggregate_level == "well":
            n0 = Z_all_raw.shape[0]
            Z_all_raw, meta_all = aggregate_to_well(Z_all_raw, meta_all)
            print(f"  well-aggregated: {n0} sites -> {Z_all_raw.shape[0]} wells")

        (Z_raw_s,), meta_s = subsample([Z_all_raw], meta_all, args.n_samples)

        branches["Raw"] = evaluate_branch(
            Z_all_raw, meta_all, Z_raw_s, meta_s,
            args.batch_keys, args.lisi_perplexity, args.no_silhouette_lisi,
            args.leiden_k, args.leiden_resolution)
        all_results["raw"] = branches["Raw"]

    # ----------------------------------------------------------------------- #
    # Auto-discovered branches  (all load Z_tr_corr.npy + meta_tr.pq)
    # ----------------------------------------------------------------------- #
    for sub_dir in discovered:
        step += 1
        name     = SUBDIR_TO_NAME.get(sub_dir.name, sub_dir.name)
        json_key = sub_dir.name
        print(f"\n[{step}/{n_total}] {name} branch ...")

        Z    = np.load(sub_dir / "Z_tr_corr.npy")
        meta = pd.read_parquet(sub_dir / "meta_tr.pq")
        print(f"  {name} embeddings: {Z.shape} (no PCA needed, already reduced)")

        if args.aggregate_level == "well":
            n0 = Z.shape[0]
            Z, meta = aggregate_to_well(Z, meta)
            print(f"  well-aggregated: {n0} sites -> {Z.shape[0]} wells")

        (Z_s,), meta_s = subsample([Z], meta, args.n_samples)

        branches[name]       = evaluate_branch(
            Z, meta, Z_s, meta_s,
            args.batch_keys, args.lisi_perplexity, args.no_silhouette_lisi,
            args.leiden_k, args.leiden_resolution)
        all_results[json_key] = branches[name]

    # ----------------------------------------------------------------------- #
    # Comparison table
    # ----------------------------------------------------------------------- #
    if branches:
        print_comparison(branches, args.batch_keys)
    else:
        print("No branches evaluated.")

    # --- Save JSON ---
    if args.out_json and all_results:
        with open(args.out_json, "w") as f:
            json.dump(all_results, f, indent=2)
        print(f"Results saved to {args.out_json}")
