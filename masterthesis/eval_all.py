#!/usr/bin/env python
"""
eval_all.py — Compare Raw + all batch-corrected embeddings side by side.

Runs silhouette, LISI, kBET and mAP (mean average precision) for each
available branch and prints a single summary table for direct comparison.

Branch discovery
----------------
All subdirectories of --embeddings-dir that contain both
    Z_tr_corr.npy  and  meta_tr.pq
are loaded automatically. This includes branches generated by:
    normalize_tvn.py, normalize_harmony.py, normalize_combat.py,
    normalize_scvi.py, normalize_mnn.py, normalize_mad.py,
    normalize_sphering.py, normalize_pipeline.py (any combination).

Raw branch is always loaded from the original .npz files + PCA.

Usage
-----
  conda activate mm_cpu

  # all discovered branches
  python masterthesis/eval_all.py \\
      --embeddings-dir checkpoints/rare-vortex-325_5x40s102/channelwise_embeddings \\
      --meta-path source_3_w_neg.pq

  # skip specific branches by subdir name
  python masterthesis/eval_all.py \\
      --embeddings-dir checkpoints/rare-vortex-325_5x40s102/channelwise_embeddings \\
      --meta-path source_3_w_neg.pq \\
      --skip-branches scvi mnn

  # skip raw, save JSON
  python masterthesis/eval_all.py \\
      --embeddings-dir checkpoints/rare-vortex-325_5x40s102/channelwise_embeddings \\
      --meta-path source_3_w_neg.pq \\
      --no-raw \\
      --out-json checkpoints/rare-vortex-325_5x40s102/channelwise_embeddings/eval_all.json
"""

