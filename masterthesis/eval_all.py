def detect_meta_path(checkpoint_dir: Path) -> Path:
    """
    Read source_types from the saved config YAML in the checkpoint dir and
    resolve the matching parquet file in the project root.

    Path layout:
      <project_root>/checkpoints/<run>/   <- checkpoint_dir  (config yaml here)
      <project_root>/                     <- project root     (parquet files here)
    """
    config_files = sorted(checkpoint_dir.glob("*_config.yaml"))
    if not config_files:
        return None
    with open(config_files[-1]) as f:   # use the most recent if multiple exist
        saved = yaml.safe_load(f) or {}
    source_types = saved.get("config", {}).get("source_types")
    if not source_types:
        return None
    project_root = checkpoint_dir.parent.parent
    meta_path = project_root / f"{source_types}.pq"
    return meta_path if meta_path.exists() else None


def load_npz_with_meta(npz_path: Path, source_3: pd.DataFrame,
                       control_key: str = "DMSO"):
    """Load raw .npz and align to metadata parquet by Metadata_Sample_ID."""
    npz = np.load(npz_path, allow_pickle=True)
    X = npz["emb"]
    names = npz["names"].astype(str)
    meta_idx = source_3.set_index("Metadata_Sample_ID", drop=False)
    aligned = meta_idx.reindex(names)
    missing = aligned["Metadata_Sample_ID"].isna().sum()
    if missing:
        raise ValueError(f"{missing} IDs in {npz_path.name} not found in metadata")
    aligned = aligned.rename(columns={
        "Metadata_Plate": "plate",
        "Metadata_Well":  "well",
        "Metadata_Batch": "batch",
        "pert_iname":     "label_id",
        "pert_iname_str": "label_name",
    })
    aligned["is_control"] = aligned["label_name"].eq(control_key)
    return X, aligned.reset_index(drop=True)


def pca_reduce(X_fit, X_transform_list, n_components):
    """Fit PCA on X_fit, transform all arrays in X_transform_list."""
    n_comp = min(n_components, X_fit.shape[1], X_fit.shape[0])
    pca = PCA(n_components=n_comp, random_state=42)
    pca.fit(X_fit)
    ev = pca.explained_variance_ratio_.sum()
    return [pca.transform(X) for X in X_transform_list], n_comp, ev


def subsample(arrays, meta, n_samples, seed=42):
    N = arrays[0].shape[0]
    if 0 < n_samples < N:
        rng = np.random.default_rng(seed)
        idx = rng.choice(N, size=n_samples, replace=False)
        idx.sort()
    else:
        idx = np.arange(N)
    return [a[idx] for a in arrays], meta.iloc[idx].reset_index(drop=True)


def _well_key_cols(meta):
    """Columns that uniquely identify a physical well (plate x well position).

    Prefers the explicit Metadata_Well_ID when present; otherwise falls back to
    (batch, plate, well), which cannot merge wells across batches/plates.
    """
    if "Metadata_Well_ID" in meta.columns:
        return ["Metadata_Well_ID"]
    return [c for c in ("batch", "plate", "well") if c in meta.columns]


def aggregate_to_well(Z, meta):
    """Collapse per-site rows to one per-well consensus profile (median Z).

    The well is the biological replicate unit (~9 imaging sites per well). Running
    retrieval/mixing metrics on raw per-site rows treats the 8 sibling sites of a
    well as 'replicates', which trivially saturates mAP/AUROC and pollutes kBET/LISI
    neighbourhoods. Aggregating first is the JUMP/copairs/Arevalo convention and the
    per-well aggregation this thesis's methods section already describes.
    """
    key = _well_key_cols(meta)
    if not key:
        return Z, meta
    groups = meta.groupby(key, sort=False).indices  # {key -> integer positions}
    n = len(groups)
    Z_out = np.empty((n, Z.shape[1]), dtype=np.float32)
    first_rows = np.empty(n, dtype=np.int64)
    for i, idx in enumerate(groups.values()):
        Z_out[i] = np.median(Z[idx], axis=0)
        first_rows[i] = idx[0]
    meta_out = meta.iloc[first_rows].reset_index(drop=True)
    return Z_out, meta_out


def discover_branches(emb_dir: Path, skip_set: set) -> list:
    """
    Scan emb_dir for subdirs that have both Z_tr_corr.npy and meta_tr.pq.
    Returns sorted list of Path objects (one per discovered branch).
    skip_set: set of lowercase subdir names to exclude.
    """
    return sorted(
        d for d in emb_dir.iterdir()
        if d.is_dir()
        and (d / "Z_tr_corr.npy").exists()
        and (d / "meta_tr.pq").exists()
        and d.name.lower() not in skip_set
    )


